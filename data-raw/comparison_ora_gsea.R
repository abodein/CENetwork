  dplyr::pull(name)

# --- Helpers -----------------------------------------------------------------
#
# The run_* helpers return every term the method could test within the network
# background, with its FDR-adjusted qvalue. Significance (qvalue < 0.05) is applied
# downstream, so that "tested but not significant" stays distinguishable from
# "never tested" (outside the ORA/GSEA universe, or node not visited by diffusion).

run_ora_go <- function(sig) {
  clusterProfiler::enrichGO(
    gene          = sig,
    keyType       = "ENSEMBL",
    OrgDb         = org.Hs.eg.db,
    ont           = "all",
    pAdjustMethod = "none",
    pvalueCutoff  = 1,
    qvalueCutoff  = 1
  )@result |>
    dplyr::filter(ID %in% GOTox) |>
    dplyr::mutate(qvalue = p.adjust(pvalue, method = "fdr"))
}

run_ora_reactome <- function(sig) {
  entrez <- AnnotationDbi::select(
    org.Hs.eg.db, keys = sig, keytype = "ENSEMBL", columns = "ENTREZID"
  ) |> na.omit() |> dplyr::pull(ENTREZID) |> unique()

  ReactomePA::enrichPathway(
    gene = entrez, pvalueCutoff = 1, pAdjustMethod = "none", readable = TRUE
  )@result |>
    dplyr::filter(ID %in% pathway_background) |>
    dplyr::mutate(qvalue = p.adjust(pvalue, method = "fdr"))
}

make_gsea_scores <- function(df_name) {
  df <- list_signature_s368[[df_name]] |> as.data.frame()
  scores <- df$log2FoldChange
  names(scores) <- stringr::str_remove(rownames(df), "_.*")
  sort(na.omit(scores), decreasing = TRUE)
}

run_gsea_go <- function(scores) {
  clusterProfiler::gseGO(
    geneList     = scores,
    OrgDb        = org.Hs.eg.db,
    keyType      = "ENSEMBL",
    ont          = "all",
    pvalueCutoff = 1,
    verbose      = FALSE
  )@result |>
    dplyr::filter(ID %in% GOTox) |>
    dplyr::mutate(qvalue = p.adjust(pvalue, method = "fdr"))
}

run_gsea_reactome <- function(scores) {
  scores_entrez <- scores |>
    as.data.frame() |>
    stats::setNames("score") |>
    tibble::rownames_to_column("ENSEMBL") |>
    dplyr::left_join(
      AnnotationDbi::select(org.Hs.eg.db, keys = names(scores),
                            keytype = "ENSEMBL", columns = "ENTREZID"),
      by = "ENSEMBL"
    ) |>
    na.omit() |>
    dplyr::group_by(ENTREZID) |>
    dplyr::summarise(score = median(score), .groups = "drop") |>
    dplyr::arrange(dplyr::desc(score)) |>
    tibble::deframe()

  ReactomePA::gsePathway(
    scores_entrez, pvalueCutoff = 1, pAdjustMethod = "none", verbose = FALSE
  )@result |>
    dplyr::filter(ID %in% pathway_background) |>
    dplyr::mutate(qvalue = p.adjust(pvalue, method = "fdr"))
}

# --- Run analyses ------------------------------------------------------------

message("ORA GO...")
ora_go_apap_all <- run_ora_go(sig_aceto)
ora_go_vpa_all  <- run_ora_go(sig_valpro)

