# --- Figure: term x method dot plot ------------------------------------------
#
# Replaces the former 3-set Venn diagrams. On liver_1.8 no panel has a triple
# intersection and pairwise overlaps are 0-2 terms, so a Venn spends a full page
# drawing empty regions. A Venn also cannot separate a term a method *tested and
# rejected* from one it never tested (outside its universe, or a node the diffusion
# never visited) — here that is an explicit third state.
#
# Colours are the project's method palette (Okabe-Ito), shared with the benchmark
# figures. Point area encodes -log10(q); the three methods use different statistics
# (permutation z-score, hypergeometric test, weighted KS), so areas are comparable
# within a method, not across.

library(ggplot2)

METHOD_COL <- c(Diffusion = "#009E73", ORA = "#E69F00", GSEA = "#CC79A7")

node_labels <- igraph::vertex_attr(liver_1.8_network) |>
  as.data.frame() |>
  dplyr::select(name, display_name)

cc      <- comparison_ora_gsea
enrichs <- list(APAP = enrich_apap, VPA = enrich_vpa)

panels <- list(
  list(compound = "APAP", ontology = "GO",       diff = "GO",      ora = "ora_go_apap",       gsea = "gsea_go_apap"),
  list(compound = "APAP", ontology = "Reactome", diff = "pathway", ora = "ora_reactome_apap", gsea = "gsea_reactome_apap"),
  list(compound = "VPA",  ontology = "GO",       diff = "GO",      ora = "ora_go_vpa",        gsea = "gsea_go_vpa"),
  list(compound = "VPA",  ontology = "Reactome", diff = "pathway", ora = "ora_reactome_vpa",  gsea = "gsea_reactome_vpa")
)

# every term each method tested in this panel, with its q-value
tested_terms <- function(p) {
  d <- enrichs[[p$compound]] |>
    dplyr::filter(type == p$diff) |>
    dplyr::transmute(term, q = padj)
  o <- cc$full[[p$ora]]  |> dplyr::transmute(term = ID, q = qvalue)
  g <- cc$full[[p$gsea]] |> dplyr::transmute(term = ID, q = qvalue)

  dplyr::bind_rows(Diffusion = d, ORA = o, GSEA = g, .id = "method") |>
    dplyr::mutate(panel = paste(p$compound, "·", p$ontology))
}

dat_tested <- purrr::map_dfr(panels, tested_terms) |>
  dplyr::mutate(status = ifelse(!is.na(q) & q < 0.05,
                                "significant", "tested, not significant"))

# Rows = every term significant for at least one method, no truncation. Ranking by
# q would be misleading here: the GSEA hits on APAP are dominated by a redundant
# cluster of nested Reactome translation sets (12 of them tie at q = 5e-09), which
# a top-N would show at the expense of the bioactivation pathways (Biological
# oxidations, Phase I, Xenobiotics, Cytochrome P450) that sit further down the list.
kept <- dat_tested |>
  dplyr::filter(status == "significant") |>
  dplyr::group_by(panel, term) |>
  dplyr::summarise(q_min = min(q), .groups = "drop")

dat <- kept |>
  tidyr::expand_grid(method = names(METHOD_COL)) |>
  dplyr::left_join(dat_tested, by = c("panel", "term", "method")) |>
  dplyr::mutate(
    # ORA reports only gene sets sharing >= 1 gene with the signature, so a term
    # missing from its @result has a zero overlap — i.e. p = 1, a result rather than
    # an absence of test. Only the diffusion (node never visited) and GSEA (gene set
    # outside the 10-500 gene range it scores) genuinely leave a term untested.
    q        = ifelse(is.na(q) & method == "ORA", 1, q),
    status   = dplyr::case_when(
      !is.na(status)  ~ status,
      method == "ORA" ~ "tested, not significant",
      TRUE            ~ "not tested"
    ),
    fill_key = ifelse(status == "significant", method, "none"),
    # every point needs a size, otherwise geom_point silently drops it — the two
    # non-significant states are exactly what this figure exists to show. A term
    # tested and nearly significant stays visibly bigger than one at q ~ 1.
    psize    = ifelse(status == "not tested", 0, -log10(pmax(q, 1e-12)))
  ) |>
  dplyr::left_join(node_labels, by = c("term" = "name")) |>
  dplyr::mutate(
    label  = stringr::str_wrap(dplyr::coalesce(display_name, term), 52),
    # zero-width space keeps the factor unique per panel while showing the bare name.
    # Facet rows read top-to-bottom, so ascending q_min puts the strongest term first.
    y_key  = forcats::fct_reorder(paste0(label, "​", panel), q_min),
    method = factor(method, levels = names(METHOD_COL)),
    status = factor(status, levels = c("significant", "tested, not significant", "not tested"))
  )

fig <- ggplot(dat, aes(x = method, y = y_key)) +
  geom_point(aes(shape = status, fill = fill_key, size = psize, colour = status),
             stroke = 0.4) +
  scale_colour_manual(
    values = c("significant" = "grey25", "tested, not significant" = "grey60",
               "not tested" = "grey80"),
    guide  = "none"
  ) +
  scale_shape_manual(
    values = c("significant" = 21, "tested, not significant" = 21, "not tested" = 4),
    name   = NULL,
    guide  = guide_legend(order = 1, override.aes = list(
      size = 3, fill = c("grey30", "white", NA), colour = c("grey30", "grey65", "grey80")))
  ) +
  scale_fill_manual(values = c(METHOD_COL, none = "white"), guide = "none") +
  scale_size(range = c(1.2, 6), limits = c(0, NA),
             name = expression(-log[10] ~ q), guide = guide_legend(order = 2)) +
  # terms carried by an inner strip rather than by the y axis, so each one sits in its
  # own framed band. facet_nested (ggh4x) merges the repeated outer strip, which plain
  # facet_grid would print once per row.
  ggh4x::facet_nested(
    rows     = vars(panel, y_key),
    scales   = "free_y", space = "free_y", switch = "y",
    labeller = labeller(y_key = function(x) sub("​.*", "", x)),
    strip    = ggh4x::strip_nested(bleed = FALSE)
  ) +
  labs(
    x = NULL, y = NULL,
    title = paste("Terms retained by network diffusion, ORA and GSEA in",
                  "acetaminophen (APAP) and valproic acid (VPA)")
  ) +
  # theme_bw-like: framed panels and filled strips, so the four compound x ontology
  # blocks read as separate categories
  theme_bw(base_size = 10) +
  theme(
    panel.border       = element_rect(colour = "grey55", fill = NA, linewidth = 0.4),
    panel.grid.major.y = element_blank(),
    panel.grid.major.x = element_line(colour = "grey90", linewidth = 0.3),
    panel.grid.minor   = element_blank(),
    panel.spacing.y    = grid::unit(0, "lines"),
    strip.placement    = "outside",
    strip.background   = element_rect(fill = "grey95", colour = "grey55", linewidth = 0.4),
    # outer strip = compound x ontology, inner strip = term
    strip.text.y.left  = element_text(angle = 0, hjust = 0, size = 8,
                                      margin = margin(2, 4, 2, 4)),
    axis.text.x        = element_text(face = "bold"),
    axis.text.y        = element_blank(),
    axis.ticks.y       = element_blank(),
    plot.title.position = "plot",
    legend.position    = "right",
    legend.key.height  = grid::unit(0.8, "lines")
  )

png("vignettes/img/comparison_dotplot.png", res = 300, width = 2900, height = 6300)
