# Generate comparison_ora_gsea.rda
#
# Pre-computes ORA and GSEA enrichment results for acetaminophen (APAP) and
# valproic acid (VPA), filtered to the hepatotoxicity-specific background
# (GOTox / Reactome pathways) present in liver_1.8_network.
#
# Input files (not shipped with the package):
#   - data/liver_1.8_network.rda        (package data)
#   - data/signature_maison.rda         (package data)
#   - <project>/papier/result_use_case_paper_1.8.Rda
#       contains res_report_aceta and res_report_valpro (report() outputs)
#       + enrich_apap / enrich_vpa (diffusion enrichment stats)
#       → generated by data-raw/result_use_case_paper.R
#   - <project>/results/signature_maison_acetaminopheme_a_valproic.Rds
#       contains full DE results with log2FoldChange for GSEA scoring
#
# Run order:
#   1. source("data-raw/result_use_case_paper.R")   # ~30-60 min
#   2. source("data-raw/comparison_ora_gsea.R")     # ~10 min

library(tidyverse)
