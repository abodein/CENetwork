sig_only <- function(res) dplyr::filter(res, qvalue < 0.05)

ora_go_apap       <- sig_only(ora_go_apap_all)
ora_go_vpa        <- sig_only(ora_go_vpa_all)
ora_reactome_apap <- sig_only(ora_reactome_apap_all)
ora_reactome_vpa  <- sig_only(ora_reactome_vpa_all)
gsea_go_apap       <- sig_only(gsea_go_apap_all)
gsea_go_vpa        <- sig_only(gsea_go_vpa_all)
gsea_reactome_apap <- sig_only(gsea_reactome_apap_all)
gsea_reactome_vpa  <- sig_only(gsea_reactome_vpa_all)

# Diffusion significant terms, thresholded like ORA/GSEA (padj < 0.05).
# report()$GOs / $pathways list *every* term present in the subnetwork, which is
# not comparable to the q < 0.05 sets of the other two methods.
diffusion_sig <- function(enrich, term_type) {
  enrich$term[enrich$type == term_type & enrich$padj < 0.05] |> na.omit() |> unique()
}

# Terms each method actually tested. Needed to tell "tested but not significant"
# apart from "never tested" — a distinction a Venn diagram cannot show.
diffusion_tested <- function(enrich, term_type) {
  enrich$term[enrich$type == term_type] |> na.omit() |> unique()
}

comparison_ora_gsea <- list(
  # Diffusion significant terms (from compute_diffusion_enrichment(), padj < 0.05)
  diffusion_go_apap      = diffusion_sig(enrich_apap, "GO"),
  diffusion_go_vpa       = diffusion_sig(enrich_vpa,  "GO"),
  diffusion_pathway_apap = diffusion_sig(enrich_apap, "pathway"),
  diffusion_pathway_vpa  = diffusion_sig(enrich_vpa,  "pathway"),

  # ORA – GO (filtered to GOTox, re-FDR, qvalue < 0.05)
  ora_go_apap = ora_go_apap,
  ora_go_vpa  = ora_go_vpa,

  # GSEA – GO (filtered to GOTox, re-FDR, qvalue < 0.05)
  gsea_go_apap = gsea_go_apap,
  gsea_go_vpa  = gsea_go_vpa,

  # ORA – Reactome (filtered to pathway_background, re-FDR, qvalue < 0.05)
  ora_reactome_apap = ora_reactome_apap,
  ora_reactome_vpa  = ora_reactome_vpa,

  # GSEA – Reactome (filtered to pathway_background, re-FDR, qvalue < 0.05)
  gsea_reactome_apap = gsea_reactome_apap,
  gsea_reactome_vpa  = gsea_reactome_vpa,

  # Full result tables (every term tested within the network background, with qvalue)
  full = list(
    ora_go_apap = ora_go_apap_all,             ora_go_vpa = ora_go_vpa_all,
    ora_reactome_apap = ora_reactome_apap_all, ora_reactome_vpa = ora_reactome_vpa_all,
    gsea_go_apap = gsea_go_apap_all,           gsea_go_vpa = gsea_go_vpa_all,
    gsea_reactome_apap = gsea_reactome_apap_all, gsea_reactome_vpa = gsea_reactome_vpa_all,
    diffusion_go_apap      = diffusion_tested(enrich_apap, "GO"),
    diffusion_go_vpa       = diffusion_tested(enrich_vpa,  "GO"),
    diffusion_pathway_apap = diffusion_tested(enrich_apap, "pathway"),
    diffusion_pathway_vpa  = diffusion_tested(enrich_vpa,  "pathway")
  )
)

