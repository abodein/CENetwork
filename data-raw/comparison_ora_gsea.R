  APAP_ORA_REACTOME       = ora_reactome_apap,
  APAP_GSEA_GO            = gsea_go_apap,
  APAP_GSEA_REACTOME      = gsea_reactome_apap,

  VPA_diffusion_GO        = diffusion_table(enrich_vpa, "GO"),
  VPA_diffusion_REACTOME  = diffusion_table(enrich_vpa, "pathway"),
  VPA_ORA_GO              = ora_go_vpa,
  VPA_ORA_REACTOME        = ora_reactome_vpa,
