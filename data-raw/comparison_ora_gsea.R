# --- Supplementary table: diffusion / ORA / GSEA side by side -----------------

node_labels <- igraph::vertex_attr(liver_1.8_network) |>
  as.data.frame() |>
  dplyr::select(name, display_name)

diffusion_table <- function(enrich, term_type) {
  enrich |>
    dplyr::filter(type == term_type) |>
    dplyr::arrange(padj) |>
    dplyr::left_join(node_labels, by = c("term" = "name")) |>
    dplyr::select(term, display_name, visit_count, mean_perm, sd_perm,
                  z_score, pvalue, padj)
}

list_results <- list(
  APAP_diffusion_GO       = diffusion_table(enrich_apap, "GO"),
  APAP_diffusion_REACTOME = diffusion_table(enrich_apap, "pathway"),
